#!/usr/bin/env python3
"""Writes docs/MODULE.md: every source file with its size and the first line of its header comment.

Run after adding or growing modules: python3 -I tools/module.py
"""
import pathlib
import re

root = pathlib.Path(__file__).resolve().parent.parent
rows = []
for f in sorted((root / "src").rglob("*.rs")):
    text = f.read_text(encoding="utf-8")
    first = next((re.sub(r"^\s*//[!/]?[\s-]*", "", l) for l in text.splitlines()
                  if re.match(r"^\s*//", l) and l.strip("/! -")), "")
    rows.append((f.relative_to(root).as_posix(), text.count("\n"), first.strip()[:140]))

out = ["# Modules (generated by tools/module.py, do not edit by hand)", "",
       "Largest files first in the size list; read only the module a task touches.", "",
       "## Largest files", "", "| lines | file |", "|---:|---|"]
out += [f"| {n} | {p} |" for p, n, _ in sorted(rows, key=lambda r: -r[1])[:12]]
out += ["", f"Total: {sum(r[1] for r in rows)} lines in {len(rows)} files.", "",
        "## All modules", "", "| file | lines | what it is |", "|---|---:|---|"]
out += [f"| {p} | {n} | {d.replace('|', '/')} |" for p, n, d in rows]
(root / "docs" / "MODULE.md").write_text("\n".join(out) + "\n", encoding="utf-8")
print(f"docs/MODULE.md: {len(rows)} files")
